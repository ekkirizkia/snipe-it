<h2 style="font-size: 14pt;">1. Definisi</h2>
<ul>
    <li><strong>Aset Perusahaan</strong>: Segala bentuk perangkat, peralatan, software, akun, akses sistem, dokumen, atau barang lain yang merupakan milik PT Duta Mandiri Anugerah Cemerlang dan digunakan untuk menunjang kegiatan operasional perusahaan.</li>
    <li><strong>Pengguna</strong>: Individu yang menerima izin penggunaan aset perusahaan sesuai tugas dan tanggung jawab pekerjaan.</li>
</ul>



<h2 style="font-size: 14pt;">2. Hak Penggunaan</h2>
<p>Pengguna diberikan hak untuk menggunakan aset perusahaan <strong>hanya untuk keperluan pekerjaan</strong> yang berkaitan dengan operasional PT Duta Mandiri Anugerah Cemerlang.</p>



<h2 style="font-size: 14pt;">3. Kewajiban Pengguna</h2>
<ol>
    <li><strong>Menjaga dan merawat</strong> aset yang dipercayakan agar tetap berfungsi dengan baik.</li>
    <li><strong>Mematuhi seluruh kebijakan dan prosedur perusahaan</strong>, termasuk kebijakan IT, keamanan data, dan SOP lainnya.</li>
    <li><strong>Tidak menggunakan aset untuk kepentingan pribadi</strong>, aktivitas ilegal, atau penggunaan yang tidak sesuai dengan tujuan perusahaan.</li>
    <li><strong>Segera melaporkan</strong> kepada perusahaan jika terjadi kerusakan, kehilangan, atau gangguan teknis.</li>
    <li><strong>Tidak memindahtangankan, meminjamkan, menjual, memodifikasi, atau merusak</strong> aset perusahaan dalam bentuk apa pun.</li>
    <li><strong>Menjaga kerahasiaan data perusahaan</strong> yang tersimpan atau dapat diakses melalui aset tersebut.</li>
</ol>



<h2 style="font-size: 14pt;">4. Larangan</h2>
<ul>
    <li>Menginstal software tidak berlisensi atau tanpa persetujuan perusahaan.</li>
    <li>Membongkar atau memodifikasi perangkat keras dan perangkat lunak tanpa izin resmi.</li>
    <li>Mengakses data atau sistem yang bukan bagian dari pekerjaannya.</li>
    <li>Menggunakan aset untuk tindakan yang melanggar hukum atau kebijakan perusahaan.</li>
</ul>



<h2 style="font-size: 14pt;">5. Tanggung Jawab Atas Kerusakan atau Kehilangan</h2>
<p>Pengguna bertanggung jawab atas kerusakan atau kehilangan aset dan wajib diceritakan secara detil kronologis, waktu, saksi, dan deskripsi lengkap saat kejadian. apabila terbukti karena:</p>
<ul>
    <li>Kelalaian atau kesalahan penggunaan,</li>
    <li>Penyimpanan yang tidak aman,</li>
    <li>Penyalahgunaan aset.</li>
</ul>

<p>PT Duta Mandiri Anugerah Cemerlang berhak untuk:</p>
<ul>
    <li>Menagihkan biaya perbaikan atau penggantian,</li>
    <li>Melakukan penarikan aset,</li>
    <li>Memberikan sanksi administratif sesuai kebijakan perusahaan.</li>
</ul>



<h2 style="font-size: 14pt;">6. Pengembalian Aset</h2>
<p>Pengguna wajib mengembalikan aset perusahaan apabila:</p>
<ul>
    <li>Diminta oleh perusahaan,</li>
    <li>Aset diganti atau diperbarui,</li>
    <li>Tugas atau penempatan berubah,</li>
    <li>Hubungan kerja berakhir.</li>
</ul>
<p>Aset harus dikembalikan dalam kondisi baik dan sesuai ketentuan perusahaan.</p>



<h2 style="font-size: 14pt;">7. Monitoring dan Audit</h2>
<p>PT Duta Mandiri Anugerah Cemerlang berhak melakukan monitoring, pemeriksaan, atau audit terhadap penggunaan aset, termasuk namun tidak terbatas pada:</p>
<ul>
    <li>Pemeriksaan fisik,</li>
    <li>Pemeriksaan software,</li>
    <li>Audit keamanan data dan aktivitas sistem.</li>
</ul>
<p>Monitoring dapat dilakukan sewaktu-waktu sesuai kebijakan perusahaan.</p>



<h2 style="font-size: 14pt;">8. Keamanan Data dan Privasi</h2>
<p>Pengguna memahami bahwa aset perusahaan dapat memiliki:</p>
<ul>
    <li>Sistem keamanan,</li>
    <li>Logging aktivitas,</li>
    <li>Monitoring penggunaan,</li>
</ul>
<p>yang bertujuan menjaga integritas dan keamanan operasional perusahaan.</p>

<p>Pengguna menyetujui bahwa perusahaan dapat memproses data aktivitas sesuai regulasi yang berlaku.</p>



<h2 style="font-size: 14pt;">9. Konsekuensi Pelanggaran</h2>
<p>Pelanggaran terhadap ketentuan ini dapat mengakibatkan:</p>
<ul>
    <li>Peringatan lisan atau tertulis,</li>
    <li>Pembatasan akses,</li>
    <li>Penarikan aset,</li>
    <li>Tindakan disiplin internal,</li>
    <li>Tindakan hukum bila diperlukan.</li>
</ul>



<h2 style="font-size: 14pt;">10. Pernyataan Persetujuan</h2>
<p>Dengan menggunakan aset perusahaan, pengguna menyatakan bahwa:</p>
<ul>
    <li>Telah memahami dan menyetujui seluruh ketentuan dalam perjanjian ini,</li>
    <li>Akan mematuhi seluruh peraturan yang berlaku,</li>
    <li>Bersedia bertanggung jawab penuh atas penggunaan aset perusahaan.</li>
</ul>

